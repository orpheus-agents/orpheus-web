import { expect, type Page } from '@playwright/test'

/** Browser writes against the real API; no model runs or external credential calls. */
export async function checkLLMCatalog(page: Page) {
  const name = `Browser account ${crypto.randomUUID().slice(0, 8)}`
  await page.getByRole('link', { name: 'LLM accounts', exact: true }).click()
  await page.getByRole('link', { name: 'Add account', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill(name)
  await page.getByLabel('Authorization mode').selectOption('api_key')
  await page.getByLabel('API key', { exact: true }).fill('sk-browser-fixture-key')
  const created = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/v1/llm-accounts' && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const response = await created
  expect(response.status()).toBe(201)
  const account = await response.json()
  expect(account.api_key_mask).toBe('sk-b...-key')
  expect(account.api_key).toBeUndefined()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  expect(await page.getByLabel('New API key').inputValue()).toBe('')
  await page.getByLabel('New API key').fill('sk-replaced-fixture-value')
  const keyForm = page.locator('form').filter({ has: page.getByLabel('New API key') })
  await keyForm.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('sk-r...alue', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Profiles', exact: true }).click()
  await page.getByRole('link', { name: 'Add profile', exact: true }).click()
  const profileName = `browser-profile-${crypto.randomUUID().slice(0, 8)}`
  await page.getByLabel('Name', { exact: true }).fill(profileName)
  await page.getByRole('button', { name: 'LLM account', exact: true }).click()
  await page.getByRole('option', { name: `${name} ${account.id.slice(0, 8)}`, exact: true }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Required field.', { exact: true })).toBeVisible()
  await page.getByLabel('Model', { exact: true }).fill('test-model')
  await page.getByLabel('Instructions', { exact: true }).fill('Preserve these instructions')
  const creation = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/v1/profiles' && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  expect((await creation).status()).toBe(201)
  await expect(page.getByRole('heading', { name: profileName, exact: true })).toBeVisible()
  await expect(page.getByLabel('Name', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Disable', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Disable', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enable', exact: true })).toBeVisible()
  // Rebind API-key -> file account under the same harness. Saving does not reactivate the profile.
  await page.getByRole('button', { name: 'LLM account', exact: true }).click()
  await page.getByRole('option', { name: 'fixture-account 00000000', exact: true }).click()
  await page.getByLabel('Model', { exact: true }).fill('different-model')
  const updated = page.waitForResponse((r) => r.url().includes('/api/v1/profiles/') && r.request().method() === 'PATCH')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const saved = await updated
  expect(saved.status()).toBe(200)
  expect(saved.request().postDataJSON()).not.toHaveProperty('active')
  expect(await saved.json()).toMatchObject({ active: false, available: false, account_id: '00000000-0000-4000-8000-000000000001', model: 'different-model', instructions: 'Preserve these instructions' })
  await expect(page.getByRole('button', { name: 'Enable', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Model profiles', exact: true })).toBeVisible()
  await page.goto(`/settings/llm-accounts/${account.id}`)
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'LLM accounts', exact: true })).toBeVisible()
  expect((await page.request.get(`/api/v1/llm-accounts/${account.id}`)).status()).toBe(404)
}

export async function checkOpenCodeAccount(page: Page) {
  const name = `OpenCode ${crypto.randomUUID().slice(0, 8)}`
  await page.getByRole('link', { name: 'Add account', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill(name)
  await page.getByLabel('Harness').selectOption('opencode')
  await page.getByLabel('Authorization mode').selectOption('api_key')
  const provider = page.getByLabel('Provider', { exact: true })
  await provider.selectOption({ label: 'Other provider…' })
  await page.getByLabel('Provider ID', { exact: true }).fill('selectel')
  await provider.selectOption('kimi-code-plan-global')
  await expect(page.getByLabel('Provider ID', { exact: true })).toHaveCount(0)
  await page.getByLabel('API key', { exact: true }).fill('subscription-fixture-key')
  const created = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith('/api/v1/llm-accounts'))
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const accountResponse = await created
  expect(accountResponse.status()).toBe(201)
  const account = await accountResponse.json()
  expect(account).toMatchObject({ harness: 'opencode', provider: 'kimi-code-plan-global', auth_mode: 'api_key' })
  await expect(page.getByText(account.provider, { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Back to accounts' }).click()
  const card = page.locator('article').filter({ has: page.getByRole('link', { name, exact: true }) })
  await expect(card).toContainText('No observation yet')
  await page.getByRole('link', { name: 'Profiles', exact: true }).click()
  await page.getByRole('link', { name: 'Add profile', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill(name.replace(' ', '-'))
  await page.getByRole('button', { name: 'LLM account', exact: true }).click()
  await page.getByRole('option', { name: `${name} ${account.id.slice(0, 8)}`, exact: true }).click()
  const effort = page.getByLabel('Reasoning effort', { exact: true })
  await effort.fill('high')
  await page.getByLabel('Model', { exact: true }).fill('k3.1-pro')
  const saved = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith('/api/v1/profiles'))
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const profileResponse = await saved
  expect(profileResponse.status()).toBe(201)
  const profile = await profileResponse.json()
  expect(profile).toMatchObject({ harness: 'opencode', account_id: account.id, model: 'k3.1-pro', opencode: { variant: 'high' } })
  await expect(page.getByRole('heading', { name: profile.name, exact: true })).toBeVisible()
  await expect(effort).toHaveValue('high')
  await effort.fill('')
  const cleared = page.waitForResponse((r) => r.request().method() === 'PATCH' && r.url().endsWith('/profiles/' + profile.id))
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  expect(await (await cleared).json()).not.toHaveProperty('opencode')
  await page.reload()
  await expect(effort).toHaveValue('')
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Model profiles', exact: true })).toBeVisible()
  await page.goto(`/settings/llm-accounts/${account.id}`)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'LLM accounts', exact: true })).toBeVisible()
}
