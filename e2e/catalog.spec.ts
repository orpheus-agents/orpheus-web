test('OpenCode profile creation and editing omit Codex options', async ({ page }) => {
  const kimi = llmAccount({ id: rid, name: 'Kimi', harness: LLMAccountHarness.opencode, provider: 'kimi-code-plan-global' })
  const profile = modelProfile({ harness: ProfileHarness.opencode, account_id: rid, account_name: 'Kimi', model: 'k3.1-pro' })
  await page.route('**/api/v1/llm-accounts?**', (route) => route.fulfill({ json: { items: [llmAccount(), kimi], next_cursor: null, prev_cursor: null } }))
  await page.route(`**/api/v1/llm-accounts/${rid}`, (route) => route.fulfill({ json: { ...kimi, api_key_mask: null } }))
  await page.route('**/api/v1/profiles', (route) => route.fulfill({ status: 201, json: profile }))
  await page.route(`**/api/v1/profiles/${rid}`, (route) => route.fulfill({ json: profile }))
  await page.goto('/settings/profiles/new')
  const account = page.getByRole('button', { name: 'LLM account', exact: true })
  const effort = page.getByLabel('Reasoning effort')
  await account.click()
  await page.getByRole('option', { name: /Team account/ }).click()
  await effort.selectOption('high')
  await account.click()
  await page.getByRole('option', { name: /Kimi/ }).click()
  await expect(effort).toHaveCount(0)
  await page.getByLabel('Name', { exact: true }).fill('kimi')
  await page.getByLabel('Model', { exact: true }).fill('k3.1-pro')
  const create = page.waitForRequest((request) => request.method() === 'POST')
  await page.getByRole('button', { name: 'Save' }).click()
  expect((await create).postDataJSON()).not.toHaveProperty('codex')
  await expect(page.getByRole('heading', { name: profile.name, exact: true })).toBeVisible()
  await expect(effort).toHaveCount(0)
  await page.getByLabel('Model', { exact: true }).fill('updated-model')
  const edit = page.waitForRequest((request) => request.method() === 'PATCH')
  await page.getByRole('button', { name: 'Save' }).click()
  expect((await edit).postDataJSON()).toEqual({ account_id: rid, model: 'updated-model', description: profile.description, instructions: '' })
})
