for (const theme of ['light', 'dark']) test(`JSON authorization editing preserves values and highlights syntax in ${theme}`, async ({ page }) => {
  const raw = '{"auth_mode":"chatgpt","tokens":{"access_token":"fake-demo-token"},"unknown":9007199254740993123}'
  let reads = 0
  const writes: { body: string | null; etag: string | undefined }[] = []
  await page.addInitScript((theme) => localStorage.setItem('orpheus_theme', theme), theme)
  await page.route(`**/api/v1/llm-accounts/${sid}`, (route) => route.fulfill({ json: { ...llmAccount(), credential_store: 'local', api_key_mask: null } }))
  await page.route(`**/api/v1/llm-accounts/${sid}/auth-file`, (route) => {
    if (route.request().method() === 'GET') { reads++; return route.fulfill({ contentType: 'application/json', headers: { ETag: '"original"' }, body: raw }) }
    writes.push({ body: route.request().postData(), etag: route.request().headers()['if-match'] })
    return route.fulfill({ status: writes.length === 1 ? 409 : 204 })
  })
  await page.goto(`/settings/llm-accounts/${sid}`)
  const back = page.getByRole('link', { name: 'Back to accounts' })
  await expect(back.locator('svg')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit authorization' })).toBeVisible()
  expect(reads).toBe(0)
  await page.getByRole('button', { name: 'Edit authorization' }).click()
  const input = page.getByRole('textbox', { name: 'Authorization file (JSON)' })
  await expect(input).toHaveText(raw)
  await expect(input).toHaveCSS('font-family', /JetBrains Mono/)
  await expect(input.locator('.text-accent-ink').first()).toBeVisible()
  await expect(input.locator('.text-danger-ink')).toHaveText('9007199254740993123')
  await input.click()
  await input.press('ControlOrMeta+End')
  await page.keyboard.insertText(' ')
  await input.press('ControlOrMeta+z')
  await expect(input).toHaveText(raw)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  const draft = raw.replace('fake-demo-token', 'pasted-фиктивный-token')
  await page.evaluate((value) => navigator.clipboard.writeText(value), draft)
  await input.press('ControlOrMeta+a')
  await input.press('ControlOrMeta+v')
  const form = page.locator('form').filter({ has: input })
  await form.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('The authorization file has changed.', { exact: false })).toBeVisible()
  await expect(input).toHaveText(draft)
  expect(writes[0]).toEqual({ body: draft, etag: '"original"' })
  expect(reads).toBe(1)
  await form.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(input).toHaveCount(0)
  expect(writes[1]).toEqual(writes[0])
})

