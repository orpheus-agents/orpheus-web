test('account choice is one searchable field with server paging, retry and keyboard selection', async ({ page }) => {
  let moreAttempts = 0
  const queries: string[] = []
  await page.route('**/api/v1/llm-accounts?**', (route) => {
    const query = new URL(route.request().url()).searchParams
    queries.push(query.toString())
    if (query.has('cursor') && ++moreAttempts === 1) return route.fulfill({ status: 503 })
    const searched = query.get('name_contains') === 'beta'
    return route.fulfill({ json: { items: [llmAccount({ id: searched || query.has('cursor') ? rid : sid, name: searched || query.has('cursor') ? 'Beta' : 'Alpha', active: !searched })], next_cursor: searched || query.has('cursor') ? null : 'next', prev_cursor: null } })
  })
  await page.route(`**/api/v1/llm-accounts/${rid}`, (route) => route.fulfill({ json: { ...llmAccount({ id: rid, name: 'Beta', active: false }), credential_store: 'local', api_key_mask: null } }))
  await page.goto('/settings/profiles/new')
  await expect(page.getByRole('link', { name: 'Back to profiles' }).locator('svg')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Apply', exact: true })).toHaveCount(0)
  await expect(page.getByRole('searchbox')).toHaveCount(0)
  const field = page.getByRole('button', { name: 'LLM account', exact: true })
  await field.click()
  await expect(page.getByRole('searchbox')).toBeFocused()
  await page.getByRole('button', { name: 'Load more' }).click()
  await expect(page.getByText('Could not load accounts.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Load more' }).click()
  await expect(page.getByRole('option', { name: `Beta ${rid.slice(0, 8)}`, exact: true })).toBeVisible()
  await expect(field).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('searchbox').fill('beta')
  await expect(page.getByRole('option', { name: `Alpha ${sid.slice(0, 8)}`, exact: true })).toHaveCount(0)
  await expect(page.getByRole('option', { name: `Beta ${rid.slice(0, 8)} · Inactive`, exact: true })).toBeVisible()
  await page.getByRole('searchbox').press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(field).toContainText('Beta')
  await expect(field).toBeFocused()
  await expect(field).toHaveAttribute('aria-expanded', 'false')
  expect(queries.at(-1)).toBe('name_contains=beta&limit=50')
  await field.click()
  await page.getByRole('searchbox').press('Escape')
  await expect(field).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByLabel('Name', { exact: true })).toHaveCSS('font-family', /JetBrains Mono/)
  await expect(page.getByLabel('Model', { exact: true })).toHaveCSS('font-family', /JetBrains Mono/)
})

